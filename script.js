function setLang(lang){
  if(!['en','zh'].includes(lang)) lang='en';
  document.documentElement.lang=lang==='zh'?'zh-Hant':'en';
  document.querySelectorAll('[data-i18n]').forEach(el=>{
    if(!el.hasAttribute('data-original')) el.setAttribute('data-original',el.textContent);
    const value=lang==='zh'?zh[el.dataset.i18n]:el.getAttribute('data-original');
    if(value!==undefined) el.textContent=value;
  });
  document.querySelectorAll('[data-placeholder-i18n]').forEach(el=>{
    if(!el.hasAttribute('data-original-placeholder')) el.setAttribute('data-original-placeholder',el.placeholder);
    el.placeholder=lang==='zh'?(zh[el.dataset.placeholderI18n]||el.getAttribute('data-original-placeholder')):el.getAttribute('data-original-placeholder');
  });
  document.querySelectorAll('[data-lang]').forEach(b=>{const active=b.dataset.lang===lang;b.classList.toggle('active',active);b.setAttribute('aria-pressed',String(active));});
  document.title=lang==='zh'?'AI Services & Solutions｜AI 與數位科技解決方案':'AI Services & Solutions | AI & Digital Technology';
  try{localStorage.setItem('site-language',lang);}catch(e){}
}

